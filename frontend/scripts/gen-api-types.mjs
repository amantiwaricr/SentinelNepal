// Generates src/types/api.gen.ts from openapi.json (exported by the backend with
// `python -m app.cli export-openapi`). Run `npm run gen:api`; CI runs `npm run gen:api:check`
// so hand edits or a stale file fail the build.
//
// A small purpose-built generator instead of openapi-typescript: that package's peer
// dependency pins TypeScript 5, and our schema uses only a handful of JSON-Schema features.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import * as prettier from 'prettier'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const SPEC = join(root, 'openapi.json')
const OUTPUT = join(root, 'src', 'types', 'api.gen.ts')

// Page[T] is written once as a generic in api.ts; multipart bodies are built by hand.
const SKIP_SCHEMA = /^(Page_|Body_)/

const name = (ref) => ref.split('/').at(-1)
const wrap = (type) => (type.includes('|') ? `(${type})` : type)
const literal = (value) => JSON.stringify(value)
// Keys that document a schema without constraining it; a schema of only these accepts anything.
const ANNOTATIONS = new Set(['title', 'description', 'default', 'examples'])

export function tsType(schema) {
  if (schema === true || schema === undefined) return 'unknown'
  if (Object.keys(schema).every((key) => ANNOTATIONS.has(key))) return 'unknown'
  if (schema.$ref) return name(schema.$ref)
  if (schema.anyOf || schema.oneOf) {
    const parts = (schema.anyOf ?? schema.oneOf).map(tsType)
    return [...new Set(parts)].join(' | ')
  }
  if (schema.enum) return schema.enum.map(literal).join(' | ')
  if ('const' in schema) return literal(schema.const)
  switch (schema.type) {
    case 'string':
      return 'string'
    case 'integer':
    case 'number':
      return 'number'
    case 'boolean':
      return 'boolean'
    case 'null':
      return 'null'
    case 'array':
      return `${wrap(tsType(schema.items))}[]`
    case 'object':
      if (schema.properties) return objectType(schema)
      return `Record<string, ${tsType(schema.additionalProperties)}>`
    default:
      throw new Error(`Unsupported schema: ${JSON.stringify(schema)}`)
  }
}

function objectType(schema) {
  const required = new Set(schema.required ?? [])
  const fields = Object.entries(schema.properties).map(
    ([key, value]) => `${key}${required.has(key) ? '' : '?'}: ${tsType(value)}`,
  )
  return `{\n${fields.join('\n')}\n}`
}

function queryName(operationId) {
  // e.g. "list_alerts_api_v1_alerts_get" -> "ListAlertsQuery"
  const base = operationId.replace(/_api_v1_.*$/, '')
  return base.replace(/(^|_)([a-z0-9])/g, (_, __, c) => c.toUpperCase()) + 'Query'
}

export function generate(spec) {
  const out = [
    '// Generated by scripts/gen-api-types.mjs from openapi.json. Do not edit by hand:',
    '// run `npm run gen:api` after `python -m app.cli export-openapi` in backend/.',
    '',
  ]
  for (const [schemaName, schema] of Object.entries(spec.components.schemas)) {
    if (SKIP_SCHEMA.test(schemaName)) continue
    if (schema.type === 'object' && schema.properties) {
      out.push(`export interface ${schemaName} ${objectType(schema)}`, '')
    } else {
      out.push(`export type ${schemaName} = ${tsType(schema)}`, '')
    }
  }
  for (const operations of Object.values(spec.paths)) {
    for (const operation of Object.values(operations)) {
      const query = (operation.parameters ?? []).filter((p) => p.in === 'query')
      if (query.length === 0) continue
      const fields = query.map((p) => {
        // Optional parameters may be omitted; null is never sent as a query value.
        const type = tsType(p.schema)
          .split(' | ')
          .filter((t) => t !== 'null')
          .join(' | ')
        return `${p.name}${p.required ? '' : '?'}: ${type}`
      })
      out.push(`export interface ${queryName(operation.operationId)} {\n${fields.join('\n')}\n}`, '')
    }
  }
  return out.join('\n')
}

async function main() {
  const spec = JSON.parse(readFileSync(SPEC, 'utf-8'))
  const options = (await prettier.resolveConfig(OUTPUT)) ?? {}
  const code = await prettier.format(generate(spec), { ...options, parser: 'typescript' })
  if (process.argv.includes('--check')) {
    let current = ''
    try {
      current = readFileSync(OUTPUT, 'utf-8')
    } catch {
      // Missing file: reported as stale below.
    }
    if (current !== code) {
      console.error('src/types/api.gen.ts is stale: run `npm run gen:api` and commit it')
      process.exit(1)
    }
    console.log('src/types/api.gen.ts is up to date')
    return
  }
  writeFileSync(OUTPUT, code, 'utf-8')
  console.log(`Wrote ${OUTPUT}`)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main()
